// [SW-BUST-v4] Cache bump forcé — l'ancienne version (futbolito-v3) servait du JS
// compilé en cache-first, bloquant les corrections frontend (notamment les alert()
// natives remplacées par des modales/toasts). Ce bump vide TOUS les anciens caches.
const CACHE_NAME = 'futbolito-v4';
const STATIC_ASSETS = [
  '/',
  '/manifest.json',
  '/icon-192.png',
  '/icon-512.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return Promise.allSettled(
        STATIC_ASSETS.map((url) =>
          cache.add(url).catch(() => {/* ignore missing assets */})
        )
      );
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      // Supprime TOUS les caches qui ne sont pas la version courante
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;

  const url = new URL(event.request.url);

  // Cache-first UNIQUEMENT pour les images et fonts — le JS et le CSS doivent
  // toujours venir du réseau pour garantir la dernière version du code.
  const isImageOrFont =
    url.pathname.match(/\.(png|jpg|jpeg|svg|ico|webp|woff2?)$/) ||
    url.pathname === '/manifest.json';

  if (isImageOrFont && url.origin === self.location.origin) {
    event.respondWith(
      caches.match(event.request).then((cached) => {
        if (cached) return cached;
        return fetch(event.request).then((response) => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        });
      })
    );
    return;
  }

  // Network-first pour TOUT le reste (JS, CSS, HTML, API)
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    fetch(event.request)
      .then((response) => {
        if (response && response.status === 200) {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
        }
        return response;
      })
      .catch(() => caches.match(event.request))
  );
});
